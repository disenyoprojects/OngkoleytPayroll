    public function run(): void {
        $calc = new AttendancePayCalculator();
        $settings = PayrollSetting::current();

        foreach ($this->newHires() as [$code, $full, $short, $role, $branchName, $type]) {
            if (Employee::withTrashed()->where('employee_code', $code)->exists()) {
                continue;
            }
            $branch = Branch::firstOrCreate(['name' => $branchName]);
            Employee::create([
                'employee_code' => $code, 'full_name' => $full, 'short_name' => $short,
                'role' => $role, 'branch_id' => $branch->id, 'employment_type' => $type,
                'shift_start' => '08:00:00', 'shift_end' => '17:00:00',
                'hire_date' => '2026-07-16', 'daily_basic_rate' => null,
            ]);
        }

        $grand = 0.0;
        foreach ($this->roster() as $code => $info) {
            $employee = Employee::withTrashed()->where('employee_code', $code)->first();
            if (! $employee) {
                $this->command?->warn("DTR2: skipped {$code} (not in roster)");
                continue;
            }

            // Idempotent: clear this employee's records for the window, then
            // recreate (avoids SQLite date-cast mismatch on updateOrCreate).
            AttendanceRecord::where('employee_id', $employee->id)
                ->whereDate('work_date', '>=', $this->day(0))
                ->whereDate('work_date', '<=', $this->day(count($info['d']) - 1))
                ->delete();

            $days = 0.0; $lates = 0; $gross = 0.0;
            foreach ($info['d'] as $i => $spec) {
                $date = $this->day($i);
                $row = $this->parse($spec);
                if ($row === null) {
                    continue;
                }
                $worked = $row['_worked'];
                unset($row['_worked']);
                $record = AttendanceRecord::create(
                    ['employee_id' => $employee->id, 'work_date' => $date, 'status' => 'approved'] + $row,
                );
                $record->setRelation('employee', $employee);
                $pay = $calc->computeForRecord($record, $settings);
                if ($pay) {
                    $gross += $pay['total'];
                    $days += $worked;
                    if ($pay['late']) { $lates++; }
                }
            }
            $grand += $gross;

            $flagD = $info['days'] === null ? 'n/a' : (abs($days - $info['days']) < 0.01 ? 'ok' : "SHEET {$info['days']}");
            $flagL = $info['lates'] === null ? 'n/a' : ($lates === $info['lates'] ? 'ok' : "SHEET {$info['lates']}");
            $this->command?->info(sprintf(
                'DTR2 %-9s %-12s worked=%-5s (%s)  lates=%-2d (%s)  gross=₱%s',
                $code, $employee->short_name, number_format($days, 1), $flagD, $lates, $flagL, number_format($gross, 2)
            ));
        }
        $this->command?->info('DTR2 TOTAL gross for Jul 16–31: ₱' . number_format($grand, 2));

        $this->loadAdjustments();
    }

    /** Allowances (paid) + cash-advance deductions dated at period end (Jul 31). */
    private function loadAdjustments(): void {
        $date = $this->day(count($this->roster()['EMP-0012']['d']) - 1); // Jul 31

        foreach ($this->allowances() as $code => $amount) {
            $employee = Employee::withTrashed()->where('employee_code', $code)->first();
            if (! $employee) { continue; }
            PayrollAdjustment::where('employee_id', $employee->id)
                ->where('label', 'Allowance (paid in cash)')
                ->whereDate('date', '>=', $this->day(0))->whereDate('date', '<=', $date)->delete();
            PayrollAdjustment::create([
                'employee_id' => $employee->id, 'date' => $date, 'label' => 'Allowance (paid in cash)',
                'category' => 'allowance', 'amount' => $amount, 'paid' => true,
                'reason' => 'ALLOWANCES sheet, Jul 16–31 2026',
            ]);
        }

        foreach ($this->cashAdvances() as $code => $amount) {
            $employee = Employee::withTrashed()->where('employee_code', $code)->first();
            if (! $employee) { continue; }
            PayrollAdjustment::where('employee_id', $employee->id)
                ->where('label', 'Cash advance')
                ->whereDate('date', '>=', $this->day(0))->whereDate('date', '<=', $date)->delete();
            PayrollAdjustment::create([
                'employee_id' => $employee->id, 'date' => $date, 'label' => 'Cash advance',
                'category' => 'deduction', 'amount' => -abs($amount), 'paid' => false,
                'reason' => 'DEDUCTIONS sheet, Jul 16–31 2026',
            ]);
        }
    }

    /** Y-m-d string for day index (0 = Jul 16). */
    private function day(int $i): string {
        return sprintf('%04d-%02d-%02d', self::YEAR, self::MONTH, self::START_DAY + $i);
    }

    private function parse(string $spec): ?array {
        $parts = explode('|', $spec);
        $type = $parts[0];

        if ($type === '-') {
            return null;
        }
        if ($type === 'P') {
            // Paid scheduled day (also TRAVEL/LEAVE/TUDING, or a scheduled day
            // with incomplete/no punches) — counts as a worked day.
            [$ss, $se] = $this->shift($parts[1] ?? '08:00-17:00');
            return $this->row($ss, $se, $ss, null, null, $se, null, 1.0);
        }
        if ($type === 'H') {
            [$ss, $se] = $this->shift($parts[1]);
            return $this->row($ss, $se, $parts[2], null, null, $this->cap($parts[3], $se, $parts[2]), 'half_day', 0.5);
        }
        if ($type === 'R') {
            // Rest day worked OT only: zero regular window, all time at rest premium.
            [$oi, $oo] = $this->shift($parts[1]);
            return $this->row($oi, $oi, $oi, null, null, $oo, null, 0.0, true);
        }

        // Worked day.
        [$ss, $se] = $this->shift($parts[1]);
        $in = $parts[2];
        $bo = ($parts[3] ?? '') !== '' ? $parts[3] : null;
        $bi = ($parts[4] ?? '') !== '' ? $parts[4] : null;
        $out = $parts[5];

        if (isset($parts[6], $parts[7]) && $parts[6] !== '' && $parts[7] !== '') {
            $otDur = $this->min($parts[7]) - $this->min($parts[6]);
            if ($otDur <= 0) { $otDur += 1440; }
            $clockOut = $this->hhmm($this->min($se) + $otDur);
        } else {
            $clockOut = $this->cap($out, $se, $in);
        }

        return $this->row($ss, $se, $in, $bo, $bi, $clockOut, null, 1.0);
    }

    private function cap(string $out, string $shiftEnd, string $in): string {
        $o = $this->min($out); $s = $this->min($in);
        if ($o <= $s) { $o += 1440; }
        return $this->hhmm(min($o, $this->min($shiftEnd)));
    }

    private function row(string $ss, string $se, string $in, ?string $bo, ?string $bi, string $out, ?string $absence, float $worked, bool $isRest = false): array {
        return [
            'shift_start' => $ss . ':00', 'shift_end' => $se . ':00',
            'clock_in' => $in . ':00', 'clock_out' => $out . ':00',
            'break_out' => $bo ? $bo . ':00' : null, 'break_in' => $bi ? $bi . ':00' : null,
            'holiday_type' => null, 'is_rest_day' => $isRest, 'absence_type' => $absence, '_worked' => $worked,
        ];
    }

    private function shift(string $range): array {
        [$a, $b] = explode('-', $range);
        return [$a, $b];
    }

    private function min(string $hhmm): int {
        [$h, $m] = array_map('intval', explode(':', $hhmm));
        return $h * 60 + $m;
    }

    private function hhmm(int $min): string {
        $min %= 1440;
        return sprintf('%02d:%02d', intdiv($min, 60), $min % 60);
    }
