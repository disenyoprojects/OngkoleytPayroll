    public function run(): void {
        $calc = new AttendancePayCalculator();
        $settings = PayrollSetting::current();

        // Add DTR staff not yet in the roster (branch/role are best-guess; adjust in-app).
        foreach ($this->newHires() as [$code, $full, $short, $role, $branchName]) {
            if (Employee::withTrashed()->where('employee_code', $code)->exists()) {
                continue;
            }
            $branch = Branch::firstOrCreate(['name' => $branchName]);
            Employee::create([
                'employee_code' => $code, 'full_name' => $full, 'short_name' => $short,
                'role' => $role, 'branch_id' => $branch->id, 'employment_type' => 'regular',
                'shift_start' => '08:00:00', 'shift_end' => '17:00:00',
                'hire_date' => '2026-07-01', 'daily_basic_rate' => null,
            ]);
        }

        $grand = 0.0;
        foreach ($this->roster() as $code => $info) {
            $employee = Employee::withTrashed()->where('employee_code', $code)->first();
            if (! $employee) {
                $this->command?->warn("DTR: skipped {$code} (not in roster)");
                continue;
            }

            $days = 0.0; $lates = 0; $gross = 0.0;
            foreach ($info['d'] as $i => $spec) {
                $date = sprintf('%04d-%02d-%02d', self::YEAR, self::MONTH, $i + 1);
                $row = $this->parse($spec, ($i + 1) === 15);
                if ($row === null) {
                    AttendanceRecord::where('employee_id', $employee->id)->whereDate('work_date', $date)->delete();
                    continue;
                }
                $worked = $row['_worked'];
                unset($row['_worked']);
                $record = AttendanceRecord::updateOrCreate(
                    ['employee_id' => $employee->id, 'work_date' => $date],
                    $row + ['status' => 'approved'],
                );
                $record->setRelation('employee', $employee);
                $pay = $calc->computeForRecord($record, $settings);
                if ($pay) {
                    $gross += $pay['total'];
                    $days += $worked;
                    if ($pay['late']) { $lates++; }
                }
            }
            $grand += $gross;

            $flagD = abs($days - $info['days']) < 0.01 ? 'ok' : "SHEET {$info['days']}";
            $flagL = $info['lates'] === null ? 'n/a' : ($lates === $info['lates'] ? 'ok' : "SHEET {$info['lates']}");
            $this->command?->info(sprintf(
                'DTR %-9s %-12s worked=%-5s (%s)  lates=%-2d (%s)  gross=₱%s',
                $code, $employee->short_name, number_format($days, 1), $flagD, $lates, $flagL, number_format($gross, 2)
            ));
        }
        $this->command?->info('DTR TOTAL gross for Jul 1–15: ₱' . number_format($grand, 2));
    }

    private function parse(string $spec, bool $isJul15): ?array {
        $holiday = $isJul15 ? 'special' : null;
        $parts = explode('|', $spec);
        $type = $parts[0];

        if ($type === '-') {
            return null;
        }
        if ($type === 'P') {
            [$ss, $se] = $this->shift($parts[1] ?? '08:00-17:00');
            return $this->row($ss, $se, $ss, null, null, $se, $holiday, null, 0.0);
        }
        if ($type === 'H') {
            [$ss, $se] = $this->shift($parts[1]);
            return $this->row($ss, $se, $parts[2], null, null, $this->cap($parts[3], $se, $parts[2]), $holiday, 'half_day', 0.5);
        }

        // Worked day.
        [$ss, $se] = $this->shift($parts[1]);
        $in = $parts[2];
        $bo = ($parts[3] ?? '') !== '' ? $parts[3] : null;
        $bi = ($parts[4] ?? '') !== '' ? $parts[4] : null;
        $out = $parts[5];

        if (isset($parts[6], $parts[7]) && $parts[6] !== '' && $parts[7] !== '') {
            $otDur = $this->min($parts[7]) - $this->min($parts[6]);
            if ($otDur <= 0) { $otDur += 1440; }
            $clockOut = $this->hhmm($this->min($se) + $otDur);
        } else {
            $clockOut = $this->cap($out, $se, $in);
        }

        return $this->row($ss, $se, $in, $bo, $bi, $clockOut, $holiday, null, 1.0);
    }

    private function cap(string $out, string $shiftEnd, string $in): string {
        $o = $this->min($out); $s = $this->min($in);
        if ($o <= $s) { $o += 1440; }
        return $this->hhmm(min($o, $this->min($shiftEnd)));
    }

    private function row(string $ss, string $se, string $in, ?string $bo, ?string $bi, string $out, ?string $holiday, ?string $absence, float $worked): array {
        return [
            'shift_start' => $ss . ':00', 'shift_end' => $se . ':00',
            'clock_in' => $in . ':00', 'clock_out' => $out . ':00',
            'break_out' => $bo ? $bo . ':00' : null, 'break_in' => $bi ? $bi . ':00' : null,
            'holiday_type' => $holiday, 'absence_type' => $absence, '_worked' => $worked,
        ];
    }

    private function shift(string $range): array {
        [$a, $b] = explode('-', $range);
        return [$a, $b];
    }

    private function min(string $hhmm): int {
        [$h, $m] = array_map('intval', explode(':', $hhmm));
        return $h * 60 + $m;
    }

    private function hhmm(int $min): string {
        $min %= 1440;
        return sprintf('%02d:%02d', intdiv($min, 60), $min % 60);
    }
